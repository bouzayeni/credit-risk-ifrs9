"""Render docs/phase3_scorecard.md from the summary written by credit_risk.scorecard.train."""

from credit_risk.scorecard.metrics import BASE_ODDS, BASE_SCORE, PDO


def table(rows: list[dict], cols: dict[str, str]) -> str:
    out = ["| " + " | ".join(cols.values()) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        cells = []
        for k in cols:
            v = r[k]
            cells.append(f"{v:,}" if isinstance(v, int) and k not in ("band", "step") else str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def pct(x: float) -> str:
    return f"{100 * x:.2f}%"


def render(s: dict) -> str:
    sp = s["splits"]
    split_rows = [
        {"split": name, "years": years, "loans": sp[name]["loans"],
         "default_rate": pct(sp[name]["default_rate"]), "gini": sp[name]["gini"], "ks": sp[name]["ks"]}
        for name, years in (("train", "2007–2014"), ("valid", "2015"), ("test", "2016–2017"))
    ]  # fmt: skip
    b = s["benchmarks_test"]
    bench_rows = [
        {"model": "Scorecard (this project)", "inputs": f"{b['scorecard']['features']} binned application features",
         "gini": b["scorecard"]["gini"], "ci": b["scorecard"]["gini_ci95"], "ks": b["scorecard"]["ks"]},
        {"model": "XGBoost", "inputs": f"{b['xgboost']['features']} raw application features, {b['xgboost']['trees']} trees",
         "gini": b["xgboost"]["gini"], "ci": b["xgboost"]["gini_ci95"], "ks": b["xgboost"]["ks"]},
        {"model": "Lending Club sub-grade", "inputs": "LC's internal model (more data than this project)",
         "gini": b["lc_sub_grade"]["gini"], "ci": b["lc_sub_grade"]["gini_ci95"], "ks": b["lc_sub_grade"]["ks"]},
        {"model": "Lending Club interest rate", "inputs": "price set from the sub-grade",
         "gini": b["lc_int_rate"]["gini"], "ci": "—", "ks": b["lc_int_rate"]["ks"]},
    ]  # fmt: skip
    year_rows = [{"year": y, **v, "default_rate": pct(v["default_rate"])}
                 for y, v in s["test_by_year"].items()]  # fmt: skip
    final_rows = [{**f, "p_value": f"{f['p_value']:.1e}"} for f in s["final_features"]]
    band_rows = [{**r, "test_default_rate": pct(r["test_default_rate"]),
                  "train_default_rate": pct(r["train_default_rate"]),
                  "scorecard_pd": pct(r["scorecard_pd"])} for r in s["score_bands"]]  # fmt: skip
    card_rows = [{**r, "share": pct(r["share"]), "bad_rate": pct(r["bad_rate"])}
                 for r in s["scorecard"]]  # fmt: skip
    iv_rows = s["iv"][:30]
    removed = ", ".join(f"`{r['feature']}` (coef {r['coef']}, p {r['p_value']:.2g})"
                        for r in s["removed_in_final_fit"]) or "none"  # fmt: skip
    corr = ", ".join(f"`{a}` (with `{b_}`)" for a, b_ in s["correlation_dropped"].items()) or "none"

    return f"""# Phase 3: application scorecard

Generated by `python -m credit_risk.scorecard.train`; every number is computed. Full detail:
[phase3_summary.json](phase3_summary.json). Target: `default_12m` (first missed payment within
12 months of issue, Phase 1), on loans with a complete 12-month window.

## Out-of-time design

The model only sees the past: bins and coefficients come from 2007–2014 loans, feature choices
from 2015 loans, and the 2016–2017 test loans were scored once, at the end.

{table(split_rows, {"split": "Split", "years": "Issued", "loans": "Loans", "default_rate": "Default rate", "gini": "Gini", "ks": "KS"})}

Test Gini 95% bootstrap interval: {sp["test"]["gini_ci95"]}.

## Results against benchmarks (test, 2016–2017)

{table(bench_rows, {"model": "Model", "inputs": "Inputs", "gini": "Gini", "ci": "95% CI", "ks": "KS"})}

By test year:

{table(year_rows, {"year": "Issued", "loans": "Loans", "default_rate": "Default rate", "gini": "Gini", "ks": "KS"})}

## Feature selection

1. **Candidates:** application fields only. Excluded on purpose: Lending Club's grade, sub-grade,
   interest rate and instalment (LC's own model and price, used as the benchmark); `addr_state`
   (scoring by location risks redlining); joint-application fields and the 14 fields collected
   from 2016 (absent from the training years).
2. **Information value** on train, binned with monotonic default rates; IV < 0.02 dropped.
3. **Correlation filter:** a feature whose WoE correlates above 0.6 with a stronger one is
   dropped: {corr}.
4. **Forward selection:** add the feature that most raises the 2015 validation Gini; stop when
   the gain is under 0.002 or at 15 features.

{table(s["selection_steps"], {"step": "Step", "added": "Feature added", "valid_gini": "Validation Gini"})}

5. **Final fit** (statsmodels, all of train). Terms with a wrong sign or p > 0.01 are removed:
   {removed}.

{table(final_rows, {"feature": "Feature", "coef": "Coefficient", "p_value": "p-value", "iv": "IV"})}

With WoE inputs (positive = safer), every coefficient is negative, as it should be.

### Information value (top 30 candidates, train)

{table(iv_rows, {"feature": "Feature", "iv": "IV", "bins": "Bins"})}

## The scorecard

Points scale: {BASE_SCORE} points = good:bad odds of {BASE_ODDS}:1, and every {PDO} points
double the odds. A loan's score is the sum of its points; higher means safer.

{table(card_rows, {"feature": "Feature", "bin": "Bin", "loans": "Train loans", "share": "Share", "bad_rate": "Default rate", "woe": "WoE", "points": "Points"})}

## Score bands

Bands are train deciles of the score; "scorecard PD" is the default probability implied by the
points scale.

{table(band_rows, {"band": "Band", "score_range": "Score", "test_loans": "Test loans", "test_default_rate": "Test default rate", "train_default_rate": "Train default rate", "scorecard_pd": "Scorecard PD"})}

Default rates fall steadily from the lowest to the highest band in both periods: the ranking
holds out of time. The level does not: the test default rate is above the train rate, so the
raw scorecard PD is too low for 2016–2017 loans. Calibrating PDs to the right level, by rating
grade, is Phase 4.

Two patterns worth knowing when reading the table:

- **Verified income scores lower than unverified.** Lending Club chose which incomes to verify
  and verified riskier-looking applications more often, so "verified" partly signals that LC
  was already worried. The scorecard learns the association; it is not a causal effect.
- **Missing bins sit near the middle.** Most missing bureau fields are on older loans, whose
  risk was close to average.

## Limitations

- **Accepted loans only.** Rejected applicants have no outcome, so the model learns from
  borrowers LC already approved (no reject inference). It ranks risk within LC's approved
  population, not across all applicants.
- **Policy changes.** LC changed its credit policy and its applicant mix over time; this is
  why the test is out-of-time, and why calibration is a separate step.
- **In-sample p-values are optimistic.** WoE is fitted on the same training data as the
  regression, so even a pure-noise feature can look significant (seen on synthetic data while
  writing the tests).
  The guard against noise is forward selection on the separate 2015 validation year, not the
  p-value filter.
- **Benchmark asymmetry.** LC's sub-grade was built with data this project does not have
  (full bureau files, its own history), so it is a ceiling, not a like-for-like competitor.
"""

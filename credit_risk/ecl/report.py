def pct(v, d=1):
    return f"{100 * v:.{d}f}%"


def money(v):
    return f"${v / 1e6:,.1f}M"


def table(rows: list[dict]) -> str:
    df = pd.DataFrame(rows)
    head = "| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns)
    return "\n".join(
        [head, *("| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False))]
    )


